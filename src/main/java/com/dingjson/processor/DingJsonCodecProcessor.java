package com.dingjson.processor;

import com.dingjson.annotation.JSONField;

import javax.annotation.processing.AbstractProcessor;
import javax.annotation.processing.RoundEnvironment;
import javax.lang.model.SourceVersion;
import javax.lang.model.element.Element;
import javax.lang.model.element.ElementKind;
import javax.lang.model.element.ExecutableElement;
import javax.lang.model.element.Modifier;
import javax.lang.model.element.PackageElement;
import javax.lang.model.element.TypeElement;
import javax.lang.model.element.VariableElement;
import javax.lang.model.type.TypeMirror;
import javax.lang.model.util.ElementFilter;
import javax.tools.Diagnostic;
import javax.tools.JavaFileObject;
import java.io.Writer;
import java.util.ArrayList;
import java.util.Collections;
import java.util.List;
import java.util.Set;

/**
 * Generates a direct codec for every {@link com.dingjson.annotation.DingJsonSerializable}
 * class: one straight-line {@code write} method (plain field reads plus buffer
 * appends) and one {@code read} method (plain field writes). This is the
 * compile-time counterpart of the reflective path — no {@code instanceof} chain,
 * no {@code Unsafe} offset arithmetic, no reflection per field — and it needs no
 * bytecode library: the output is ordinary Java source compiled by javac.
 * <p>
 * Generation is best effort. Anything the generated code could not reproduce
 * exactly (inherited private fields, final fields, generic classes, non-Date
 * {@code @JSONField(format)}) aborts generation for that class with a compiler
 * note, and DingJson silently keeps using reflection — the annotation is a pure
 * speed-up, never a requirement.
 */
public class DingJsonCodecProcessor extends AbstractProcessor {

    private static final String ANNOTATION = "com.dingjson.annotation.DingJsonSerializable";
    private static final String SUFFIX = "$$DingJsonCodec";

    @Override
    public Set<String> getSupportedAnnotationTypes() {
        return Collections.singleton(ANNOTATION);
    }

    @Override
    public SourceVersion getSupportedSourceVersion() {
        return SourceVersion.latestSupported();
    }

    @Override
    public boolean process(Set<? extends TypeElement> annotations, RoundEnvironment roundEnv) {
        TypeElement annotation = processingEnv.getElementUtils().getTypeElement(ANNOTATION);
        if (annotation == null) {
            return false;
        }
        for (Element element : roundEnv.getElementsAnnotatedWith(annotation)) {
            if (element.getKind() != ElementKind.CLASS) {
                error(element, "@DingJsonSerializable applies to classes only; no codec generated");
                continue;
            }
            try {
                generate((TypeElement) element);
            } catch (Abort abort) {
                note(element, "no codec generated (" + abort.getMessage()
                        + "); DingJson keeps using reflection for " + element.getSimpleName());
            } catch (Exception e) {
                error(element, "DingJson codec generation failed: " + e);
            }
        }
        return true;
    }

    /** Signals that this class must stay on the reflective path. */
    private static final class Abort extends Exception {
        private static final long serialVersionUID = 1L;

        Abort(String reason) {
            super(reason);
        }
    }

    private void generate(TypeElement type) throws Exception {
        if (type.getModifiers().contains(Modifier.ABSTRACT)) {
            throw new Abort("abstract class");
        }
        if (!type.getTypeParameters().isEmpty()) {
            throw new Abort("generic class");
        }
        String pkg = packageOf(type);
        List<FieldSpec> fields = collectFields(type, pkg);
        requireNoArgConstructor(type, pkg);

        String binaryName = processingEnv.getElementUtils().getBinaryName(type).toString();
        String simpleName = pkg.isEmpty() ? binaryName : binaryName.substring(pkg.length() + 1);
        String generatedName = simpleName + SUFFIX;

        StringBuilder src = new StringBuilder(2048);
        if (!pkg.isEmpty()) {
            src.append("package ").append(pkg).append(";\n\n");
        }
        src.append("/** Generated by DingJson from @DingJsonSerializable. Do not edit. */\n");
        src.append("public final class ").append(generatedName)
                .append(" implements com.dingjson.codec.DingJsonCodec<")
                .append(type.getQualifiedName()).append("> {\n\n");

        emitWrite(src, type, fields);
        emitRead(src, type, fields);
        src.append("}\n");

        JavaFileObject file = processingEnv.getFiler()
                .createSourceFile(pkg.isEmpty() ? generatedName : pkg + "." + generatedName, type);
        try (Writer writer = file.openWriter()) {
            writer.write(src.toString());
        }
    }

    // ── field collection ──────────────────────────────────────────

    private static final class FieldSpec {
        final String javaName;
        final String jsonName;
        final TypeMirror type;
        final boolean write;
        final boolean read;
        final String format;
        final boolean date;
        final boolean primitive;

        FieldSpec(VariableElement field) {
            this.javaName = field.getSimpleName().toString();
            this.type = field.asType();
            JSONField jf = field.getAnnotation(JSONField.class);
            this.jsonName = jf != null && !jf.name().isEmpty() ? jf.name() : javaName;
            this.write = jf == null || jf.serialize();
            this.read = jf == null || jf.deserialize();
            this.format = jf != null ? jf.format() : "";
            this.primitive = type.getKind().isPrimitive();
            this.date = type.toString().equals("java.util.Date");
        }

        /** Type usable in a cast / TypeReference; generics keep their arguments. */
        String sourceType() {
            return type.toString();
        }

        boolean parameterized() {
            return sourceType().indexOf('<') >= 0;
        }
    }

    private List<FieldSpec> collectFields(TypeElement type, String beanPackage) throws Abort {
        List<FieldSpec> fields = new ArrayList<>();
        TypeElement current = type;
        while (current != null && !current.getQualifiedName().contentEquals("java.lang.Object")) {
            for (VariableElement field : ElementFilter.fieldsIn(current.getEnclosedElements())) {
                Set<Modifier> mods = field.getModifiers();
                if (mods.contains(Modifier.STATIC) || mods.contains(Modifier.TRANSIENT)) {
                    continue;
                }
                if (field.getSimpleName().toString().indexOf('$') >= 0) {
                    continue; // synthetic (outer-instance reference and friends)
                }
                if (mods.contains(Modifier.FINAL)) {
                    throw new Abort("final field " + field.getSimpleName());
                }
                if (mods.contains(Modifier.PRIVATE)) {
                    throw new Abort("private field " + field.getSimpleName()
                            + " of " + current.getSimpleName());
                }
                if (!mods.contains(Modifier.PUBLIC)
                        && !packageOf(current).equals(beanPackage)) {
                    throw new Abort("field " + field.getSimpleName() + " is not accessible from "
                            + "the generated class (declared in another package)");
                }
                FieldSpec spec = new FieldSpec(field);
                if (spec.format.length() > 0 && !spec.date) {
                    throw new Abort("@JSONField(format) on non-Date field " + spec.javaName);
                }
                fields.add(spec);
            }
            TypeMirror superclass = current.getSuperclass();
            if (superclass == null) {
                break;
            }
            Element superElement = processingEnv.getTypeUtils().asElement(superclass);
            current = superElement instanceof TypeElement ? (TypeElement) superElement : null;
        }
        return fields;
    }

    private void requireNoArgConstructor(TypeElement type, String beanPackage) throws Abort {
        boolean declaredAny = false;
        for (ExecutableElement ctor : ElementFilter.constructorsIn(type.getEnclosedElements())) {
            declaredAny = true;
            if (!ctor.getParameters().isEmpty()) {
                continue;
            }
            Set<Modifier> mods = ctor.getModifiers();
            if (mods.contains(Modifier.PRIVATE)) {
                throw new Abort("private no-arg constructor");
            }
            if (!mods.contains(Modifier.PUBLIC) && !pkgOfEnclosing(type).equals(beanPackage)) {
                throw new Abort("no-arg constructor is not accessible from the generated class");
            }
            return;
        }
        if (declaredAny) {
            throw new Abort("no no-arg constructor");
        }
        // no declared constructor → implicit default constructor
        if (type.getModifiers().contains(Modifier.PUBLIC) || pkgOfEnclosing(type).equals(beanPackage)) {
            return;
        }
        throw new Abort("implicit no-arg constructor is not accessible");
    }

    private String pkgOfEnclosing(TypeElement type) {
        return packageOf(type);
    }

    private String packageOf(TypeElement type) {
        PackageElement pkg = processingEnv.getElementUtils().getPackageOf(type);
        return pkg.getQualifiedName().toString();
    }

    // ── code emission ─────────────────────────────────────────────

    private void emitWrite(StringBuilder src, TypeElement type, List<FieldSpec> fields) {
        String bean = type.getQualifiedName().toString();
        src.append("    @Override\n")
                .append("    public void write(").append(bean).append(" b, StringBuilder out, int depth,\n")
                .append("                       com.dingjson.DingJsonConfig config) {\n")
                .append("        out.append('{');\n");
        for (FieldSpec f : fields) {
            if (!f.write) {
                continue;
            }
            String key = "KEY_" + f.javaName;
            String value = "b." + f.javaName;
            if (f.date) {
                src.append("        com.dingjson.serializer.CodecSupport.writeDate(out, ").append(key)
                        .append(", ").append(value).append(", ")
                        .append(javaLiteral(f.format)).append(", depth, config);\n");
                continue;
            }
            String helper = primitiveHelper(f, "write");
            if (helper != null) {
                src.append("        com.dingjson.serializer.CodecSupport.").append(helper)
                        .append("(out, ").append(key).append(", ").append(value).append(");\n");
            } else {
                src.append("        com.dingjson.serializer.CodecSupport.writeRef(out, ").append(key)
                        .append(", ").append(value).append(", depth, config);\n");
            }
        }
        src.append("        out.append('}');\n")
                .append("    }\n\n");
        emitConstants(src, fields);
    }

    private void emitRead(StringBuilder src, TypeElement type, List<FieldSpec> fields) {
        String bean = type.getQualifiedName().toString();
        src.append("    @Override\n")
                .append("    @SuppressWarnings(\"unchecked\")\n")
                .append("    public ").append(bean)
                .append(" read(com.dingjson.element.JSONObject src, com.dingjson.DingJsonConfig config) {\n")
                .append("        ").append(bean).append(" b = new ").append(bean).append("();\n");
        for (FieldSpec f : fields) {
            if (!f.read) {
                continue;
            }
            src.append("        if (src.containsKey(").append(javaLiteral(f.jsonName)).append(")) {\n")
                    .append("            java.lang.Object v = src.get(")
                    .append(javaLiteral(f.jsonName)).append(");\n");
            String helper = primitiveHelper(f, "to");
            if (f.date) {
                src.append("            b.").append(f.javaName)
                        .append(" = com.dingjson.serializer.CodecSupport.toDate(v, ")
                        .append(javaLiteral(f.format)).append(", config);\n");
            } else if (helper != null) {
                src.append("            b.").append(f.javaName)
                        .append(" = com.dingjson.serializer.CodecSupport.").append(helper)
                        .append("(v, config);\n");
            } else if (f.parameterized()) {
                src.append("            b.").append(f.javaName).append(" = (").append(f.sourceType())
                        .append(") com.dingjson.serializer.CodecSupport.convert(v, TYPE_")
                        .append(f.javaName).append(", config);\n");
            } else {
                src.append("            b.").append(f.javaName).append(" = (").append(f.sourceType())
                        .append(") com.dingjson.serializer.CodecSupport.convert(v, ")
                        .append(f.sourceType()).append(".class, config);\n");
            }
            src.append("        }\n");
        }
        src.append("        return b;\n")
                .append("    }\n\n");
    }

    private void emitConstants(StringBuilder src, List<FieldSpec> fields) {
        StringBuilder body = new StringBuilder();
        for (FieldSpec f : fields) {
            if (f.write) {
                body.append("    private static final String KEY_").append(f.javaName)
                        .append(" = com.dingjson.serializer.CodecSupport.key(")
                        .append(javaLiteral(f.jsonName)).append(");\n");
            }
            if (f.read && !f.primitive && f.parameterized()) {
                body.append("    private static final java.lang.reflect.Type TYPE_").append(f.javaName)
                        .append(" = new com.dingjson.TypeReference<").append(f.sourceType())
                        .append(">() { }.getType();\n");
            }
        }
        if (body.length() > 0) {
            src.append("    // Precomputed constants: built once per class, not per instance.\n")
                    .append(body).append('\n');
        }
    }

    private static String primitiveHelper(FieldSpec f, String prefix) {
        if (!f.primitive || f.javaName == null) {
            return null;
        }
        String name;
        switch (f.type.getKind()) {
            case INT:     name = "Int"; break;
            case LONG:    name = "Long"; break;
            case DOUBLE:  name = "Double"; break;
            case FLOAT:   name = "Float"; break;
            case BOOLEAN: name = "Boolean"; break;
            case SHORT:   name = "Short"; break;
            case BYTE:    name = "Byte"; break;
            case CHAR:    name = "Char"; break;
            default:      return null;
        }
        return prefix + name;
    }

    /** Renders a Java string literal. */
    private static String javaLiteral(String value) {
        StringBuilder sb = new StringBuilder(value.length() + 2);
        sb.append('"');
        for (int i = 0; i < value.length(); i++) {
            char c = value.charAt(i);
            switch (c) {
                case '"':  sb.append("\\\""); break;
                case '\\': sb.append("\\\\"); break;
                case '\n': sb.append("\\n"); break;
                case '\r': sb.append("\\r"); break;
                case '\t': sb.append("\\t"); break;
                default:
                    if (c < 0x20) {
                        sb.append(String.format("\\u%04x", (int) c));
                    } else {
                        sb.append(c);
                    }
            }
        }
        return sb.append('"').toString();
    }

    private void note(Element element, String message) {
        processingEnv.getMessager().printMessage(Diagnostic.Kind.NOTE, message, element);
    }

    private void error(Element element, String message) {
        processingEnv.getMessager().printMessage(Diagnostic.Kind.ERROR, message, element);
    }
}
